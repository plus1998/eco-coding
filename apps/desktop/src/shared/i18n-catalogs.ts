export function expectedIpcErrorKey(message: string): I18nKey | undefined {
  if (INVALID_IPC_REQUEST_MESSAGES.has(message)) {
    return "native.error.invalidRequest";
  }
  if (MISSING_IPC_REQUIRED_MESSAGES.has(message)) {
    return "native.error.missingRequired";
  }
  if (message === "Workspace path is required." || message === "Directory path is required.") {
    return "native.error.workspaceRequired";
  }
  if (message === "请选择文件夹，而不是文件。") {
    return "native.error.selectFolder";
  }
  if (message === "Thread was not found.") {
    return "native.error.threadNotFound";
  }
  if (message === "请先停止当前运行后再删除对话。") {
    return "native.error.stopRunFirst";
  }
  if (message === "Wait for the current run to finish." || message === "请等待当前运行结束后再修改配置。") {
    return "native.error.waitForRun";
  }
  if (message === "上下文正在压缩中，请稍候。") {
    return "native.error.contextCompacting";
  }
  if (
    message === "No pending clarification for this tool use." ||
    message === "No pending Bash approval for this tool use." ||
    message === "No pending plan approval is active for this thread." ||
    message === "找不到待批准的计划。" ||
    message === "This thread is not waiting for plan approval."
  ) {
    return "native.error.pendingApprovalNotFound";
  }
  if (
    message === "Pending follow-up was not found or cannot be escalated." ||
    message === "Pending follow-up was not found or can no longer be edited." ||
    message === "Pending follow-up was not found or cannot be cancelled." ||
    message === "Pending follow-up was not found or cannot be updated."
  ) {
    return "native.error.pendingFollowUpNotFound";
  }
  if (message === "Thread is not accepting queued follow-up messages.") {
    return "native.error.threadNotAccepting";
  }
  if (message === "没有可导出的子代理模板。") {
    return "native.error.noExportableData";
  }
  if (message === "Skill is not present in a supported user Skills directory.") {
    return "native.error.skillNotFound";
  }
  if (
    message === "Failed to dismiss clarification." ||
    message === "Failed to submit clarification." ||
    message === "Failed to resolve Bash approval." ||
    message === "Codex plan approval cannot use the Claude approval bridge."
  ) {
    return "native.error.operationUnavailable";
  }
  if (INVALID_IMPORT_MESSAGES.has(message)) {
    return "native.error.invalidImport";
  }
  if (PROTECTED_CONFIGURATION_MESSAGES.has(message)) {
    return "native.error.protectedConfiguration";
  }
  if (
    message === "没有已配置的候选模型，无法生成提交信息。请在 Provider 设置中添加候选模型。" ||
    message === "没有可用的候选模型，无法生成提交信息。" ||
    message === "未指定 Git 提交模型，无法生成提交信息。请在提交窗口中选择生成模型。" ||
    message.startsWith("候选模型所属 Provider 未配置或已禁用：") ||
    message.startsWith("Git 提交模型已不在候选模型列表中：")
  ) {
    return "native.error.modelConfiguration";
  }
  if (message === "没有可提交的变更。") {
    return "native.error.noChanges";
  }
  if (message === "模型未能生成有效的提交信息，请手动填写。") {
    return "native.error.commitMessageUnavailable";
  }
  if (message === "抓取远程更新失败。") {
    return "native.error.gitFetchFailed";
  }
  if (
    message.startsWith("找不到主 Agent 配置：") ||
    message.startsWith("找不到主 Agent 提示词：") ||
    message.startsWith("找不到子代理编排：") ||
    message === "Thread runtime configuration is missing."
  ) {
    return "native.error.configurationUnavailable";
  }
  if (message === "排队的后续消息缺少可发送内容。") {
    return "native.error.followUpContentMissing";
  }
  if (message === "Cursor ACP 暂不支持带图后续消息。") {
    return "native.acpFollowUpAttachmentsUnsupported";
  }
  if (message === "Cursor ACP 不支持中断当前轮次插入后续消息；消息会在本轮结束后发送。") {
    return "native.acpFollowUpEscalateUnsupported";
  }
  if (
    message === "该节点缺少 SDK 检查点，无法安全回滚。" ||
    message === "该节点缺少运行事件索引，无法安全回滚。" ||
    message === "没有可恢复的 SDK 会话，无法回到该节点。" ||
    message === "SDK 会话工作目录不存在，无法回到该节点。"
  ) {
    return "native.error.rewindUnavailable";
  }
  if (message === "Codex Core 不可用：未找到可执行的 Codex CLI。请安装工作区依赖或设置 CODEX_EXECUTABLE。") {
    return "native.codexUnavailable";
  }
  return undefined;
}

export function translateCatalog(
  locale: AppLocale,
  key: I18nKey,
  variables: Record<string, string | number> = {},
): string {
  const catalog = i18nCatalogs[locale].translation;
  const fallback = i18nCatalogs["en-US"].translation;
  let value = (catalog[key] ?? fallback[key] ?? key) as string;
  for (const [name, replacement] of Object.entries(variables)) {
    value = value.replaceAll(`{{${name}}}`, String(replacement));
  }
  return value;
}
